#pragma once

#include "AddonAccessPolicy.h"
#include "Database.h"
#include "MutationOperationRepository.h"

#include <cstdint>
#include <string>

class AccountabilityEventRepository;

namespace vdrsuite::mediatools { class MediaToolsImportRunLock; }

namespace vdrsuite::addons {

// Root/admin/operator package work is NOT performed by this Core component.
// A frozen gate affects every backend in the shared MutationOperation store.
// All future media.import reservations read it in the same SQLite write
// transaction as operation creation, even across separate Suite processes.
enum class MaintenanceFenceStatus {
    ok,
    forbidden,
    invalid,
    revisionConflict,
    ownershipActive,
    ownershipMismatch,
    freezeRequired,
    unavailable,
};

struct MaintenanceFenceState {
    MaintenanceFenceStatus status = MaintenanceFenceStatus::unavailable;
    bool frozen = false;
    std::int64_t revision = 0; // schema exists, absent row -> unfrozen rev 0
    bool ownershipActive = false; // no token leaks through read()
};

// Token is generated by the trusted Core owner from the OS CSPRNG,
// returned once and never written to a log. The frozen owner row survives
// process death; recovering an abandoned owner is a separate gated task.
struct MaintenanceOwnershipResult {
    MaintenanceFenceState state;
    std::string token;
    bool acquired() const { return state.status == MaintenanceFenceStatus::ok &&
                                    state.ownershipActive && token.size() == 32; }
};

struct MaintenanceFenceAuditContext {
    std::string eventId;
    std::string occurredAt;
};

// Private Core-only administrator gate; not an API route or package hook.
// Fencing new reservations cannot stop an already executing Agent child.
// Package replacement still requires complete drain, provenance and consent.
class AddonMediaImportMaintenanceFence {
public:
    AddonMediaImportMaintenanceFence(
        Database& db,
        vdrsuite::operations::MutationOperationRepository& operations,
        AccountabilityEventRepository& audit)
        : db_(db), operations_(operations), audit_(audit) {}

    MaintenanceFenceState read(const RequestSecurityContext& actor) const;

    // Core-only admission of an exclusive maintenance owner, with both
    // durable revision CAS and the currently held protected kernel lock.
    // This is a coordination primitive, NEVER a package permit.
    MaintenanceOwnershipResult claimOwnership(
        const RequestSecurityContext& actor,
        std::int64_t expectedRevision,
        const vdrsuite::mediatools::MediaToolsImportRunLock& exclusive,
        const MaintenanceFenceAuditContext& auditContext);

    // Release only while the same exclusive lock and exact opaque Core token
    // are present. This preserves frozen=true. Unfreezing remains a later,
    // separately audited administrator action after maintenance completion.
    MaintenanceFenceState releaseOwnership(
        const RequestSecurityContext& actor,
        std::int64_t expectedRevision, const std::string& token,
        const vdrsuite::mediatools::MediaToolsImportRunLock& exclusive,
        const MaintenanceFenceAuditContext& auditContext);

    MaintenanceFenceState setFrozen(
        const RequestSecurityContext& actor, bool frozen,
        std::int64_t expectedRevision,
        const MaintenanceFenceAuditContext& auditContext);

private:
    Database& db_;
    vdrsuite::operations::MutationOperationRepository& operations_;
    AccountabilityEventRepository& audit_;
};

} // namespace vdrsuite::addons
